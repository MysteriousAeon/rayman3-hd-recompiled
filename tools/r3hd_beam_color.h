// HD+ power-up canister colour restoration (D-219, E-447). Installed as include/rex/r3hd_beam_color.h by
// tools/r3hd_beam_runtime_patch.py and used by the host file read path (HostPathFile::ReadSync) only.
//
// What the title has (RE_NOTES "Canister energy pages"): the power-up beam pages `sfx/trans_ray` and
// `sfx/trans_colonne` of the Xbox 360 HD release are the original PC pages with the colour channels rotated,
// HD (R, G, B) = PC (B, R, G), so the purple beams of the 2003 PC release are orange. Each has one material in each of
// the 39 level bundles that carry it (fact_40 also draws a second element with it). The canister rings above and
// below the can use the particle page `sfx/ago_blueripple` (fix bundle only): purple in PC, redrawn orange in HD.
// The ball pages of the same effect stay purple.
//
// With R3HD_BEAM_COLOR=restored a read of a listed bundle returns the listed pages with the inverse rotation,
// new (R, G, B) = HD (G, B, R), applied to the two RGB565 endpoints of every DXT1 block of the base level and the mip
// chain; texel indices change only to keep the block's mode when the endpoint order flips. Exact: no decode, no
// recompression. A page is restored only when the file has the listed size, the page's stored bytes have the listed
// hash and the result has the listed hash; otherwise the read is returned as it is. Nothing is written to disk or to
// guest memory outside the buffer the title asked to have filled. A data-only mod (M33) is applied after this and wins.
// The table carries offsets, sizes and hashes only: no texel of the title is in this file.
// tools/r3hd_beam_color.py generates the table and is the reference transform.

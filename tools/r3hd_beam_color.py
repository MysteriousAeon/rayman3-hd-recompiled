"""HD+ power-up canister colour restoration (D-219): reference transform and table generator for tools/r3hd_beam_color.h.

The Xbox 360 HD release's `sfx\\trans_ray` and `sfx\\trans_colonne` beam pages are the original PC pages with their
colour channels rotated: HD (R, G, B) = PC (B, R, G) (E-447 per-pixel comparison). The canister ring page
`sfx\\ago_blueripple` was redrawn for HD in the same orange palette (PC: a purple ring). The restoration is the inverse rotation,
new (R, G, B) = HD (G, B, R), applied exactly to each DXT1 block's two RGB565 endpoints; the texel indices are only
remapped when the endpoint order has to change to keep the block's mode. No decode, no recompression, no texel of the
title in this repository: the header lists file names, sizes, offsets and FNV-1a 64 hashes only.

  python tools/r3hd_beam_color.py table [GAMEDATAbin]   print the generated table block for the header
  python tools/r3hd_beam_color.py check [GAMEDATAbin]   header table == table from the extracted data (skips if absent)
  python tools/r3hd_beam_color.py selftest              block transform invariants (no game data)
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'tools' / 'r3hd_beam_color.h'
DATA = ROOT / 'private' / 'extracted' / '5841123F' / 'GAMEDATAbin'
# Canister energy pages (E-447): the vertical beam (`trans_ray`, `trans_colonne`, 39 level bundles) and the
# upper/lower rings (`ago_blueripple`, the shared fix bundle only). The beam pages are the PC pages rotated; the
# ring page is redrawn HD art in the rotated (orange) palette, so the same inverse rotation returns it to purple.
PAGES = ('trans_ray.dds', 'trans_colonne.dds', 'ago_blueripple.dds')
BEGIN, END = '// --- generated by tools/r3hd_beam_color.py table ---\n', '// --- end generated ---\n'


def fnv1a(data):
    h = 0xCBF29CE484222325
    for x in data:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def rotate565(c):
    r, g, b = c >> 11, (c >> 5) & 63, c & 31
    return (((g * 62 + 63) // 126) << 11) | (((b << 1) | (b >> 4)) << 5) | r


def flip_pairs(x, three_colour):
    """Index byte with endpoints swapped: 4-colour 0<->1, 2<->3; 3-colour 0<->1 (2 = midpoint, 3 = transparent)."""
    return x ^ (((~x) >> 1) & 0x55) if three_colour else x ^ 0x55


def block(stored):
    """One DXT1 block as the bundle stores it (each 16-bit word byte-swapped) -> restored block, same layout."""
    s = bytearray(stored)
    c0, c1 = struct.unpack_from('>HH', s, 0)
    n0, n1 = rotate565(c0), rotate565(c1)
    idx = s[4:8]
    if c0 > c1:                      # four colours: keep n0 > n1
        if n0 < n1:
            n0, n1, idx = n1, n0, bytes(flip_pairs(x, False) for x in idx)
        elif n0 == n1:
            idx = bytes(4)           # all four palette entries are n0 here; equal endpoints would mean 3-colour mode
    elif n0 > n1:                    # three colours + transparent: keep n0 <= n1
        n0, n1, idx = n1, n0, bytes(flip_pairs(x, True) for x in idx)
    struct.pack_into('>HH', s, 0, n0, n1)
    s[4:8] = idx
    return bytes(s)


def blob(data):
    assert len(data) % 8 == 0
    return b''.join(block(data[i:i + 8]) for i in range(0, len(data), 8))


def entries(bhf):
    b = bhf.read_bytes()
    n, = struct.unpack_from('>I', b, 0)
    assert len(b) == 4 + n * 0x114
    for i in range(n):
        o = 4 + i * 0x114
        s1, o1, s2, o2 = struct.unpack_from('>4I', b, o)
        yield b[o + 16:o + 0x114].split(b'\0')[0].decode('latin1'), s1, o1, s2, o2


def collect(data_dir):
    out = []
    for bhf in sorted(data_dir.rglob('*.bhf'), key=lambda p: p.name.lower()):
        rows = list(entries(bhf))
        pages = [r for r in rows if r[0].lower().replace('\\', '/').split('/')[-1] in PAGES]
        if not pages:
            continue
        btf = bhf.with_suffix('.btf')
        b = btf.read_bytes()
        spans = [(o, o + s) for _, s1, o1, s2, o2 in rows for o, s in ((o1, s1), (o2, s2)) if s]
        got = []
        for name, s1, o1, s2, o2 in pages:
            for o, s in ((o1, s1), (o2, s2)):
                assert s and s % 8 == 0 and o + s <= len(b), (btf.name, name)
                assert sum(a < o + s and o < e for a, e in spans) == 1, ('shared bytes', btf.name, name)
            parts = [b[o1:o1 + s1], b[o2:o2 + s2]]
            got.append((name.split('\\')[-1].lower(), (o1, o2), (s1, s2), [fnv1a(p) for p in parts],
                        [fnv1a(blob(p)) for p in parts]))
        out.append((btf.name.lower(), len(b), got))
    return out


def render(rows):
    lines = [BEGIN]
    for i, (_, _, pages) in enumerate(rows):
        lines.append(f'constexpr Page kPages{i}[] = {{\n')
        for name, off, size, stored, restored in pages:
            lines.append(f'    {{"{name}", {{0x{off[0]:X}, 0x{off[1]:X}}}, {{0x{size[0]:X}, 0x{size[1]:X}}},\n'
                         f'     {{0x{stored[0]:016X}ull, 0x{stored[1]:016X}ull}}, '
                         f'{{0x{restored[0]:016X}ull, 0x{restored[1]:016X}ull}}}},\n')
        lines.append('};\n')
    lines.append('constexpr Bundle kBundles[] = {\n')
    for i, (file, size, pages) in enumerate(rows):
        lines.append(f'    {{"{file}", {size}, kPages{i}, {len(pages)}}},\n')
    lines.append('};\n' + END)
    return ''.join(lines)


def header_table():
    text = HEADER.read_text(encoding='utf-8')
    return text[text.index(BEGIN):text.index(END) + len(END)]


def selftest():
    # Rotation: pure red/green/blue endpoints go to blue/red/green.
    assert rotate565(0xF800) == 0x001F and rotate565(0x07E0) == 0xF800 and rotate565(0x001F) == 0x07E0
    assert rotate565(0xFFFF) == 0xFFFF and rotate565(0) == 0
    for c in range(0x10000):                      # inverse direction loses at most the low green bit
        r, g, b = c >> 11, (c >> 5) & 63, c & 31
        back = rotate565(rotate565(rotate565(c)))
        assert back >> 11 == r and back & 31 == b and abs(((back >> 5) & 63) - g) <= 1, hex(c)
    # Mode preserved and the palette is the rotated palette for every order case.
    cases = [(0xF800, 0x07E0), (0x07E0, 0xF800), (0x1234, 0x1234), (0x8000, 0x0001), (0x0841, 0x0840)]
    for c0, c1 in cases:
        for idx in (b'\x00\x55\xaa\xff', b'\xe4\x1b\x93\x6c'):
            src = struct.pack('>HH', c0, c1) + idx
            out = block(src)
            n0, n1 = struct.unpack_from('>HH', out, 0)
            assert (c0 > c1) == (n0 > n1) or (rotate565(c0) == rotate565(c1)), (hex(c0), hex(c1))
            assert len(out) == 8 and block(src) == out
            for k in range(16):
                i_src = (idx[k // 4] >> (2 * (k % 4))) & 3
                i_out = (out[4 + k // 4] >> (2 * (k % 4))) & 3
                want = palette(rotate565(c0), rotate565(c1), c0 > c1)[i_src]
                assert palette(n0, n1, n0 > n1)[i_out] == want, (hex(c0), hex(c1), k)
    print('r3hd_beam_color selftest PASS')


def palette(c0, c1, four):
    def rgb(c):
        return (c >> 11, (c >> 5) & 63, c & 31)
    a, b = rgb(c0), rgb(c1)
    if four:
        return [a, b, tuple((2 * x + y) / 3 for x, y in zip(a, b)), tuple((x + 2 * y) / 3 for x, y in zip(a, b))]
    return [a, b, tuple((x + y) / 2 for x, y in zip(a, b)), 'transparent']


def main(argv):
    cmd = argv[1] if len(argv) > 1 else 'selftest'
    if cmd == 'selftest':
        return selftest()
    data = Path(argv[2]) if len(argv) > 2 else DATA
    if not data.is_dir():
        print(f'r3hd_beam_color {cmd} SKIP: no extracted game data at {data}')
        return 0
    rows = collect(data)
    text = render(rows)
    if cmd == 'table':
        sys.stdout.write(text)
        return 0
    if cmd == 'check':
        pages = sum(len(p) for _, _, p in rows)
        same = text == header_table()
        print(f'r3hd_beam_color check {"PASS" if same else "FAIL"}: {len(rows)} bundles, {pages} pages')
        return 0 if same else 1
    raise SystemExit(__doc__)


if __name__ == '__main__':
    sys.exit(main(sys.argv) or 0)

"""Offline documentation inventory, stable ID index and consolidation checks.

No builds, game processes, network access or third-party modules. --write-index
updates only KNOWLEDGE_INDEX.md; all other operations are read-only.
"""
import argparse
import collections
import json
from pathlib import Path
import re
import subprocess
import unicodedata
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "docs/maintenance/baseline.json"
INDEX = ROOT / "KNOWLEDGE_INDEX.md"
BOOKS = ("DECISIONS.md", "EXPERIMENTS.md", "RE_NOTES.md", "RESEARCH.md")


def git_text(ref, name):
    return subprocess.check_output(["git", "show", f"{ref}:{name}"], cwd=ROOT).decode("utf-8")


def canonical(text):
    return text.replace("\r\n", "\n")


def headings(text):
    counts = collections.Counter()
    result = []
    fenced = False
    for line_number, line in enumerate(text.splitlines(), 1):
        if line.startswith(("```", "~~~")):
            fenced = not fenced
        match = re.match(r"^#{1,6}\s+(.+?)\s*#*\s*$", line)
        if fenced or not match:
            continue
        title = match[1]
        slug = re.sub(r"<[^>]*>", "", title).lower()
        slug = "".join(c for c in slug if c in "_- " or unicodedata.category(c)[0] in "LN")
        slug = slug.replace(" ", "-")
        number = counts[slug]
        counts[slug] += 1
        result.append((line_number, title, slug + (f"-{number}" if number else "")))
    return result


def records():
    ids = collections.defaultdict(list)
    for name, prefix in (("DECISIONS.md", "D"), ("EXPERIMENTS.md", "E")):
        rows = headings((ROOT / name).read_text(encoding="utf-8"))
        for line, title, slug in rows:
            # E-290/E-291 were originally recorded at the end of their headings.
            match = re.search(r"\b" + prefix + r"-(\d+)\b", title)
            if match:
                ids[f"{prefix}-{int(match[1]):03}"].append((name, line, title, slug))
        if prefix == "D":
            # D-163's title lost its heading marker before this maintenance task.
            text = (ROOT / name).read_text(encoding="utf-8")
            title = "v1.1.0 final: maintainer acceptance; public containers resealed from RC1; statue correction accepted"
            if title in text and "D-163" not in ids:
                line = text[:text.index(title)].count("\n") + 1
                ids["D-163"].append((name, line, "Unheaded v1.1.0 final acceptance record (between D-164 and D-162)", ""))
    return ids


def index_text():
    out = ["# Knowledge index", "", "Current authority: [project state](PROJECT_STATE.md), [active task](CURRENT_TASK.md),",
           "[agent rules](AGENTS.md), [operating procedures](AGENT_WORKFLOWS.md).", "",
           "Read summaries first; search a relevant heading rather than loading an entire evidence book.",
           "Paths in the workflow manual remain relative to the repository root.", "",
           "## Historical lookup", "",
           "[State history](PROJECT_STATE_HISTORY.md) and [task history](CURRENT_TASK_HISTORY.md) preserve",
           "the pre-consolidation records verbatim. Their status and approval queues are historical.",
           "Old references to AGENTS milestone sections now resolve by searching AGENT_WORKFLOWS.md.",
           "For removed state/task headings, search the same heading in the corresponding history.", "",
           "The four evidence books retain their paths, headings and technical text. Their failed and",
           "superseded results remain evidence, not current work authorization.", "",
           "## Decision and experiment IDs", "",
           "One index row is the canonical lookup for each ID; multiple links preserve addenda and follow-ups.",
           "D-163 is an existing unheaded record between D-164 and D-162. E-290/E-291 occur at the ends",
           "of their original headings. E-300 was reserved on an independent branch (E-301); no record",
           "is present here. It is a documented allocation gap, not a newly invented experiment.", "",
           "Generated by `python tools/docs_check.py --write-index`; do not edit the generated lists.", ""]
    for key, rows in sorted(records().items()):
        links = [f"[{title}]({name}" + (f"#{slug}" if slug else "") + ")" for name, _, title, slug in rows]
        out.append(f"- **{key}** — " + "; ".join(links))
    for name in ("RE_NOTES.md", "RESEARCH.md", "AGENT_WORKFLOWS.md"):
        out.extend(["", f"## {name} headings", ""])
        for _, title, slug in headings((ROOT / name).read_text(encoding="utf-8")):
            out.append(f"- [{title}]({name}#{slug})")
    return "\n".join(out) + "\n"


def links(names, source=None):
    errors = []
    total = 0
    for name in names:
        text = source[name] if source is not None else (ROOT / name).read_text(encoding="utf-8")
        text = re.sub(r"(?ms)^(```|~~~).*?^\1[^\n]*", "", text)
        for match in re.finditer(r"!?\[[^\]\n]*\]\(([^\n)]+)\)", text):
            dest = match[1].strip().split(' "', 1)[0].strip("<>")
            if "`" in dest or re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", dest):
                continue
            total += 1
            parts = urlsplit(dest)
            target = ((ROOT / name).parent / unquote(parts.path)).resolve() if parts.path else ROOT / name
            if not target.exists():
                errors.append(f"{name}: missing {dest}")
            elif parts.fragment and target.suffix.lower() == ".md":
                relative = target.relative_to(ROOT).as_posix()
                body = source[relative] if source is not None and relative in source else target.read_text(encoding="utf-8")
                anchors = {row[2] for row in headings(body)}
                anchors.update(re.findall(r'<a\s+(?:name|id)=[\"\']([^\"\']+)', body))
                if unquote(parts.fragment) not in anchors:
                    errors.append(f"{name}: missing anchor {dest}")
    return total, errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-index", action="store_true")
    parser.add_argument("--baseline-links", action="store_true", help="Inspect committed baseline Markdown links only")
    args = parser.parse_args()
    if args.write_index:
        INDEX.write_bytes(index_text().encode("utf-8"))
    baseline = json.loads(BASE.read_text())
    errors = []
    ref = baseline["head"]
    if args.baseline_links:
        names = subprocess.check_output(["git", "ls-tree", "-r", "--name-only", ref], cwd=ROOT, text=True).splitlines()
        names = [n for n in names if n.endswith(".md")]
        source = {n: git_text(ref, n) for n in names}
        total, broken = links(names, source)
        print(json.dumps({"markdown_files": len(names), "relative_links": total, "broken_references": broken}, indent=2))
        return bool(broken)
    # Preserve every byte of historical text after Git's platform newline normalization.
    for name in BOOKS:
        old = canonical(git_text(ref, name))
        new = canonical((ROOT / name).read_text(encoding="utf-8"))
        if old not in new:
            errors.append(f"Historical text altered or dropped: {name}")
    for name in ("PROJECT_STATE", "CURRENT_TASK"):
        if canonical(git_text(ref, name + ".md")) != canonical((ROOT / (name + "_HISTORY.md")).read_text(encoding="utf-8")):
            errors.append(f"History differs: {name}")
    if canonical(git_text(ref, "AGENTS.md")) not in canonical((ROOT / "AGENT_WORKFLOWS.md").read_text(encoding="utf-8")):
        errors.append("Original agent procedures not preserved")
    if INDEX.read_text(encoding="utf-8") != index_text():
        errors.append("Knowledge index is stale")
    names = subprocess.check_output(["git", "ls-files", "*.md"], cwd=ROOT, text=True).splitlines()
    names += [p.name for p in ROOT.glob("*.md") if p.name not in names]
    total, broken = links(names)
    errors.extend(broken)
    ids = records()
    missing = [f"D-{i:03}" for i in range(1, 168) if f"D-{i:03}" not in ids]
    missing += [f"E-{i:03}" for i in range(1, 361) if f"E-{i:03}" not in ids and i != 300]
    errors.extend("Missing ID: " + key for key in missing)
    print(json.dumps({"markdown_files": len(names), "relative_links": total, "broken_references": broken,
                      "decision_ids": sum(k.startswith("D") for k in ids),
                      "experiment_ids": sum(k.startswith("E") for k in ids),
                      "missing_ids": missing, "reserved_ids": ["E-300"],
                      "historical_multi_heading_ids": {k: len(v) for k, v in ids.items() if len(v) > 1},
                      "errors": errors}, indent=2))
    return bool(errors)


if __name__ == "__main__":
    raise SystemExit(main())

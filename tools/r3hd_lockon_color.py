"""HD+ out-of-range lock-on indicator colour restoration (D-221): reference transform and table generator for
tools/r3hd_lockon_color.h.

The out-of-range lock-on indicator (macro87 material 40C872DC, E-451/E-452) draws the fix bundle page
`sfx\\ago_targetfar`. The original PC page is four blue corner arcs; the Xbox 360 HD release redrew it as an eight-dash
ring in a single orange ramp (green about 0.42 x red, blue 0). The restoration keeps the HD artwork and maps each DXT1
endpoint's red intensity onto the blue ramp measured from the PC page and the PC on-screen reference:

    I = red widened to 8 bits;  new (R, G, B) = (0.070 I, 0.720 I, 1.520 I), each clamped to 255, rounded to 565.

At the HD page's peak (I = 168) this is about (12, 121, 255). Exact per endpoint: texel indices are only remapped when the
endpoint order has to change to keep the block's mode; no decode, no recompression, no texel of the title in this
repository (the header lists offsets, sizes and FNV-1a 64 hashes only).

  python tools/r3hd_lockon_color.py table [GAMEDATAbin]   print the generated table block for the header
  python tools/r3hd_lockon_color.py check [GAMEDATAbin]   header table == table from the extracted data (skips if absent)
  python tools/r3hd_lockon_color.py selftest              block transform invariants (no game data)
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'tools' / 'r3hd_lockon_color.h'
DATA = ROOT / 'private' / 'extracted' / '5841123F' / 'GAMEDATAbin'
PAGES = ('ago_targetfar.dds',)
BUNDLES = ('fix.bhf',)
GAIN = (70, 720, 1520)          # per mille of the widened red intensity -> R, G, B
BEGIN, END = '// --- generated by tools/r3hd_lockon_color.py table ---\n', '// --- end generated ---\n'


def fnv1a(data):
    h = 0xCBF29CE484222325
    for x in data:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def map565(c):
    r5 = c >> 11
    i = (r5 << 3) | (r5 >> 2)
    r, g, b = (min(255, (i * k + 500) // 1000) for k in GAIN)
    return (((r * 31 + 127) // 255) << 11) | (((g * 63 + 127) // 255) << 5) | ((b * 31 + 127) // 255)


def flip_pairs(x, three_colour):
    """Index byte with endpoints swapped: 4-colour 0<->1, 2<->3; 3-colour 0<->1 (2 = midpoint, 3 = transparent)."""
    return x ^ (((~x) >> 1) & 0x55) if three_colour else x ^ 0x55


def block(stored):
    """One DXT1 block as the bundle stores it (each 16-bit word byte-swapped) -> restored block, same layout."""
    s = bytearray(stored)
    c0, c1 = struct.unpack_from('>HH', s, 0)
    n0, n1 = map565(c0), map565(c1)
    idx = s[4:8]
    if c0 > c1:                      # four colours: keep n0 > n1
        if n0 < n1:
            n0, n1, idx = n1, n0, bytes(flip_pairs(x, False) for x in idx)
        elif n0 == n1:
            idx = bytes(4)           # all four palette entries are n0 here; equal endpoints would mean 3-colour mode
    elif n0 > n1:                    # three colours + transparent: keep n0 <= n1
        n0, n1, idx = n1, n0, bytes(flip_pairs(x, True) for x in idx)
    struct.pack_into('>HH', s, 0, n0, n1)
    s[4:8] = idx
    return bytes(s)


def blob(data):
    assert len(data) % 8 == 0
    return b''.join(block(data[i:i + 8]) for i in range(0, len(data), 8))


def entries(bhf):
    b = bhf.read_bytes()
    n, = struct.unpack_from('>I', b, 0)
    assert len(b) == 4 + n * 0x114
    for i in range(n):
        o = 4 + i * 0x114
        s1, o1, s2, o2 = struct.unpack_from('>4I', b, o)
        yield b[o + 16:o + 0x114].split(b'\0')[0].decode('latin1'), s1, o1, s2, o2


def collect(data_dir):
    out = []
    for bhf in (data_dir / name for name in BUNDLES):
        rows = list(entries(bhf))
        pages = [r for r in rows if r[0].lower().replace('\\', '/').split('/')[-1] in PAGES]
        btf = bhf.with_suffix('.btf')
        b = btf.read_bytes()
        spans = [(o, o + s) for _, s1, o1, s2, o2 in rows for o, s in ((o1, s1), (o2, s2)) if s]
        got = []
        for name, s1, o1, s2, o2 in pages:
            for o, s in ((o1, s1), (o2, s2)):
                assert s and s % 8 == 0 and o + s <= len(b), (btf.name, name)
                assert sum(a < o + s and o < e for a, e in spans) == 1, ('shared bytes', btf.name, name)
            parts = [b[o1:o1 + s1], b[o2:o2 + s2]]
            got.append((name.split('\\')[-1].lower(), (o1, o2), (s1, s2), [fnv1a(p) for p in parts],
                        [fnv1a(blob(p)) for p in parts]))
        assert len(got) == len(PAGES), (bhf.name, got)
        out.append((btf.name.lower(), len(b), got))
    return out


def render(rows):
    lines = [BEGIN]
    for i, (_, _, pages) in enumerate(rows):
        lines.append(f'constexpr Page kPages{i}[] = {{\n')
        for name, off, size, stored, restored in pages:
            lines.append(f'    {{"{name}", {{0x{off[0]:X}, 0x{off[1]:X}}}, {{0x{size[0]:X}, 0x{size[1]:X}}},\n'
                         f'     {{0x{stored[0]:016X}ull, 0x{stored[1]:016X}ull}}, '
                         f'{{0x{restored[0]:016X}ull, 0x{restored[1]:016X}ull}}}},\n')
        lines.append('};\n')
    lines.append('constexpr Bundle kBundles[] = {\n')
    for i, (file, size, pages) in enumerate(rows):
        lines.append(f'    {{"{file}", {size}, kPages{i}, {len(pages)}}},\n')
    lines.append('};\n' + END)
    return ''.join(lines)


def header_table():
    text = HEADER.read_text(encoding='utf-8')
    return text[text.index(BEGIN):text.index(END) + len(END)]


def palette(c0, c1, four):
    def rgb(c):
        return (c >> 11, (c >> 5) & 63, c & 31)
    a, b = rgb(c0), rgb(c1)
    if four:
        return [a, b, tuple((2 * x + y) / 3 for x, y in zip(a, b)), tuple((x + 2 * y) / 3 for x, y in zip(a, b))]
    return [a, b, tuple((x + y) / 2 for x, y in zip(a, b)), 'transparent']


def selftest():
    # Black stays black; full red maps to the clamped blue ramp; the HD peak (red 168) lands near (12, 121, 255).
    assert map565(0) == 0 and map565(0x07E0) == 0 and map565(0x001F) == 0
    assert map565(0xF800) == ((((18 * 31 + 127) // 255) << 11) | (((184 * 63 + 127) // 255) << 5) | 31)
    peak = map565(21 << 11)                          # red5 21 -> 8-bit 173
    assert peak & 31 == 31 and 28 <= (peak >> 5) & 63 <= 32 and peak >> 11 <= 2, hex(peak)
    for r5 in range(32):                             # monotonic in red; green and blue of the input are ignored
        assert all(map565((r5 << 11) | x) == map565(r5 << 11) for x in (0x7E0, 0x1F, 0x5A5))
        if r5:
            a, b = map565((r5 - 1) << 11), map565(r5 << 11)
            assert (a & 31) <= (b & 31) and ((a >> 5) & 63) <= ((b >> 5) & 63), r5
    # Mode preserved and the palette is the mapped palette for every order case.
    cases = [(0xF800, 0x07E0), (0x07E0, 0xF800), (0x1234, 0x1234), (0x8000, 0x0001), (0x0841, 0x0840),
             (0xA000, 0xA7E0), (0xA7E0, 0xA000)]
    for c0, c1 in cases:
        for idx in (b'\x00\x55\xaa\xff', b'\xe4\x1b\x93\x6c'):
            src = struct.pack('>HH', c0, c1) + idx
            out = block(src)
            n0, n1 = struct.unpack_from('>HH', out, 0)
            assert (c0 > c1) == (n0 > n1) or (map565(c0) == map565(c1)), (hex(c0), hex(c1))
            assert len(out) == 8 and block(src) == out
            for k in range(16):
                i_src = (idx[k // 4] >> (2 * (k % 4))) & 3
                i_out = (out[4 + k // 4] >> (2 * (k % 4))) & 3
                want = palette(map565(c0), map565(c1), c0 > c1)[i_src]
                assert palette(n0, n1, n0 > n1)[i_out] == want, (hex(c0), hex(c1), k)
    print('r3hd_lockon_color selftest PASS')


def main(argv):
    cmd = argv[1] if len(argv) > 1 else 'selftest'
    if cmd == 'selftest':
        return selftest()
    data = Path(argv[2]) if len(argv) > 2 else DATA
    if not data.is_dir():
        print(f'r3hd_lockon_color {cmd} SKIP: no extracted game data at {data}')
        return 0
    rows = collect(data)
    text = render(rows)
    if cmd == 'table':
        sys.stdout.write(text)
        return 0
    if cmd == 'check':
        pages = sum(len(p) for _, _, p in rows)
        same = text == header_table()
        print(f'r3hd_lockon_color check {"PASS" if same else "FAIL"}: {len(rows)} bundles, {pages} pages')
        return 0 if same else 1
    raise SystemExit(__doc__)


if __name__ == '__main__':
    sys.exit(main(sys.argv) or 0)
